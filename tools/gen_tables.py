"""Write pd_tables.h: the lookup tables the DSP code uses instead of floating point.

  gen_tables.py OUT.h [--fs RATE]

The rate is fixed at build time (44118 Hz by default, what the Pocket AMP's I2S runs at)."""
import argparse
import math

ap = argparse.ArgumentParser()
ap.add_argument("out")
ap.add_argument("--fs", type=int, default=44118)
a = ap.parse_args()
fs = a.fs
if not 32000 <= fs <= 96000:
    raise SystemExit("fs must be 32000..96000")


def rows(vals, per=12):
    return ",\n".join("    " + ", ".join(str(v) for v in vals[i:i + per]) for i in range(0, len(vals), per))


# sine, Q15, 1024 points plus a guard point for interpolation
sine = [round(32767 * math.sin(2 * math.pi * i / 1024)) for i in range(1025)]

# phase increment a sample for MIDI notes 0..127 (2^32 = one cycle)
note_inc = [min(round(440 * 2 ** ((n - 69) / 12) / fs * 2 ** 32), 2 ** 31 - 1) for n in range(128)]

# the amp's tone stack (a Chamberlin SVF): its frequency coefficient 2 sin(pi fc / fs), Q15, for cutoff index 0..256:
# fc = 20 Hz * 2^(10 k / 256) (20 Hz .. 20.5 kHz), held below fs / 6 where the filter stays stable
svf_f = []
for k in range(257):
    fc = min(20 * 2 ** (10 * k / 256), fs / 6)
    svf_f.append(min(round(32768 * 2 * math.sin(math.pi * fc / fs)), 32767))

# the trapezoidal SVF's (pd_svf) frequency coefficient tan(pi fc / fs), Q24, for the same index; fc = 20 Hz .. 20.5 kHz,
# held below 0.45 fs (that filter is stable at any cutoff)
svf_g = [round(2 ** 24 * math.tan(math.pi * min(20 * 2 ** (10 * k / 256), 0.45 * fs) / fs)) for k in range(257)]

# segment times in samples for a parameter index 0..256: 1 ms .. 10 s, exponential
times = [max(1, round(fs * 0.001 * 10000 ** (k / 256))) for k in range(257)]

# LFO rates for a parameter index 0..256: 0.05 Hz * 2^(8 k / 256) (0.05 .. 12.8 Hz), as a phase increment a sample and
# in 1/100 Hz (for the display)
lfo_hz = [0.05 * 2 ** (8 * k / 256) for k in range(257)]
lfo_inc = [round(h / fs * 2 ** 32) for h in lfo_hz]
lfo_chz = [round(h * 100) for h in lfo_hz]

# first-order all-pass coefficient (tan(pi fc / fs) - 1) / (tan + 1), Q15, at the SVF's cutoffs (20 Hz * 2^(10 k / 256)),
# held below fs / 4
ap_a = []
for k in range(257):
    t = math.tan(math.pi * min(20 * 2 ** (10 * k / 256), fs / 4) / fs)
    ap_a.append(max(-32767, min(32767, round(32768 * (t - 1) / (t + 1)))))

# a 12AX7 gain stage (Koren's triode model: mu 100, ex 1.4, kg1 1060, kp 600, kvb 300; 300 V through 100k, grid at
# -1.5 V, the grid's conduction above 0 V as a soft limit): the input -2 .. 2 (+-1 = +-1.5 V on the grid) to the plate's
# swing, inverted back and scaled to unit gain at rest; stored halved (Q15: 0.5 = 16384)
def triode_curve():
    mu, ex, kg1, kp, kvb, bp, rp = 100.0, 1.4, 1060.0, 600.0, 300.0, 300.0, 100e3

    def plate_v(eg):
        lo, hi = 0.0, bp
        for _ in range(60):
            m = (lo + hi) / 2
            e1 = m / kp * math.log1p(math.exp(min(kp * (1 / mu + eg / math.sqrt(kvb + m * m)), 500)))
            ip = 2 * e1 ** ex / kg1 / 1000 if e1 > 0 else 0.0   # Koren's mA
            if m - (bp - ip * rp) > 0:
                hi = m
            else:
                lo = m
        return (lo + hi) / 2

    def grid(x):
        eg = -1.5 + 1.5 * x
        return eg if eg < 0 else 0.4 * math.tanh(eg / 0.4)

    e0, d = plate_v(grid(0)), 1e-4
    slope = (plate_v(grid(-d)) - plate_v(grid(d))) / (2 * d)
    return [round(16384 * (e0 - plate_v(grid(-2 + 4 * k / 256))) / slope) for k in range(257)]


tube = triode_curve()

with open(a.out, "w") as f:
    f.write(f"""/* generated by tools/gen_tables.py --fs {fs}: do not edit */
#ifndef PD_TABLES_H
#define PD_TABLES_H
#include <stdint.h>

#define PD_FS {fs}u

static const int16_t PD_SINE[1025] = {{
{rows(sine)}
}};

static const uint32_t PD_NOTE_INC[128] = {{
{rows(note_inc, 8)}
}};

static const int16_t PD_SVF_F[257] = {{
{rows(svf_f)}
}};

static const uint32_t PD_SVF_G[257] = {{
{rows(svf_g, 10)}
}};

static const uint32_t PD_TIME[257] = {{
{rows(times, 10)}
}};

static const uint32_t PD_LFO_INC[257] = {{
{rows(lfo_inc, 10)}
}};

static const uint16_t PD_LFO_CHZ[257] = {{
{rows(lfo_chz)}
}};

static const int16_t PD_AP_A[257] = {{
{rows(ap_a)}
}};

static const int16_t PD_TUBE[257] = {{
{rows(tube)}
}};

#endif
""")
