def ink(nibbles, s):
    xs = [i % s for i, v in enumerate(nibbles) if v]
    ys = [i // s for i, v in enumerate(nibbles) if v]
    return (min(xs), min(ys), max(xs) + 1, max(ys) + 1) if xs else (0, 0, 0, 0)


def main():
    out = Path(sys.argv[1])
    cps = {name: cp for cp, name in TTFont(FONT).getBestCmap().items()}
    missing = [g for _, g in ICONS if g not in cps]
    if missing:
        raise SystemExit(f"not in fukiai.ttf: {missing}")
    lines = ["/* generated by tools/gen_icons.py from assets/fonts/fukiai.ttf (MIT): do not edit */",
             "#ifndef UI_ICONS_H", "#define UI_ICONS_H", "#include <stdint.h>", "",
             "enum {"] + [f"    IC_{n}," for n, _ in ICONS] + ["    IC_COUNT", "};", ""]
    total = 0
    for s in SIZES:
        data, inks = bytearray(), []
        for _, g in ICONS:
            b, _ = ar.raster_icon(FONT, s, cps[g])
            nib = [(b[i >> 1] >> (0 if i & 1 else 4)) & 15 for i in range(s * s)]
            data += b
            inks += list(ink(nib, s))
        lines.append(ar.c_array(f"IC{s}_DATA", "uint8_t", list(data), 24, "0x{:02x}"))
        lines.append(ar.c_array(f"IC{s}_INK", "uint8_t", inks, 24))
        total += len(data) + len(inks)
    lines += ["", "#endif", ""]
    out.write_text("\n".join(lines))
    print(f"icons: {len(ICONS)} x sizes {SIZES} = {total} B -> {out}")


if __name__ == "__main__":
    main()
